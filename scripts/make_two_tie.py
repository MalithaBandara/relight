"""Generate the multi-tie demo scenario (scenarios/two_tie_demo.json).

A synthetic feeder with two normally-open ties (relight/grid_twotie.py), built to show the switching planner offering
several safe plans for one fault. One pole down on Elm Avenue trips the main recloser; the customers beyond it can
come back through the east tie, the north tie, or both. This is a demonstration of the planner, not a benchmark:
the network, customers and fault are all invented. Fixed seed.
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from relight.config import SCENARIO_DIR
from relight.packs import network

SEED = 7


def build_scenario() -> dict:
    rng = random.Random(SEED)
    pack = {"locale": "us", "languages": ["en"], "start_hour": 16, "network": {"type": "twotie"}}
    feeder, db = network({"pack": pack})

    def customers_on(section: str):
        return [c for t in feeder.transformers_on(section) for c in db.customers_on(t)]

    pole_sec = "B1-B2"
    near = customers_on(pole_sec)
    assert len(near) >= 3, "need customers on the faulted section"
    fault = {"id": "F1", "title": f"Snapped pole on {feeder.sections[pole_sec].street}", "kind": "pole_down",
             "section": pole_sec, "device": "REC-MAIN", "street": feeder.sections[pole_sec].street,
             "near_house": near[0].house_no}

    events = [{"t": t, "type": "scada", "device": "REC-MAIN", "event": ev}
              for t, ev in ((30, "trip"), (32, "reclose"), (36, "trip"), (41, "lockout"))]
    n = 0

    def complaint(t: int, cust, symptom: str, hazard: str, text: str, ch: str = "call") -> None:
        nonlocal n
        n += 1
        events.append({"t": t, "type": "complaint", "id": f"C{n}", "channel": ch, "language": "en", "from": cust.phone,
                       "text": text, "truth": {"street": cust.street, "house_no": cust.house_no, "symptom": symptom,
                                               "hazard": hazard, "account_no": cust.account_no, "fault": "F1"}})

    c0 = near[0]
    complaint(45, c0, "no_power", "pole_down",
              f"A pole has snapped and is blocking {c0.street} near number {c0.house_no}. The power is out.")
    complaint(80, near[1], "no_power", "none", f"No power at {near[1].house_no} {near[1].street}.", "sms")
    # everyone beyond the recloser is dark: a few callers from each branch
    for sid in ("B0-B1", "B2-B3", "B2-B6", "B1-B4", "B4-B5"):
        pool = customers_on(sid)
        rng.shuffle(pool)
        for k, c in enumerate(pool[:3]):
            complaint(90 + 30 * n, c, "no_power", "none",
                      f"The power went out at {c.house_no} {c.street} and the whole street is dark.",
                      "call" if k == 0 else "sms")
    events.sort(key=lambda e: e["t"])

    crews = [{"id": "CREW-L1", "name": "Demo Line Crew 1", "skills": ["line", "bucket_truck"], "base": "SUB"},
             {"id": "CREW-L2", "name": "Demo Line Crew 2", "skills": ["line", "bucket_truck"], "base": "SUB"},
             {"id": "CREW-T1", "name": "Demo Troubleshooter", "skills": ["troubleshooter"], "base": "SUB"}]
    scenario = {
        "id": "two_tie_demo", "title": "Pole down with two ties (switching demo, synthetic feeder)",
        "external": False,
        "pack": pack, "duration_s": 1500,
        "notes": ("Synthetic demonstration of multi-tie switching: invented feeder, customers and fault, one pole down "
                  "that can be restored through the east tie, the north tie or both. Generated by "
                  "scripts/make_two_tie.py (seed 7). Not a benchmark."),
        "crews": crews, "faults": [fault], "events": events,
    }
    out = SCENARIO_DIR / "two_tie_demo.json"
    out.write_text(json.dumps(scenario, indent=1), encoding="utf-8")
    print(f"Created {out} with 1 fault and {len(events)} events.")
    return scenario


if __name__ == "__main__":
    build_scenario()
